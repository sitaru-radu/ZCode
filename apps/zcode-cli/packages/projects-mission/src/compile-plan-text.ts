/**
 * Text-level helpers for the script generator: literal emission, template escaping, the worker
 * brief and the static declarations the generated script opens with.
 *
 * Everything here is pure string work. A generated script is compiled as a plain TypeScript
 * script inside a function body (no imports, no `declare`, no `export`), so the two escaping
 * rules that matter are the ones for double-quoted string literals and template literals.
 */

import type { ValidationCommand } from './compile-plan-types.js';

/** A double-quoted TypeScript string literal with fully escaped content. */
export function stringLiteral(value: string): string {
  return JSON.stringify(value);
}

/**
 * Escape the inside of a template literal: backticks end it, `${` starts an interpolation.
 * Backslashes are left alone because the only template literal we emit is a `String.raw` one,
 * where `\` is literal (a path like `src\a.ts` must survive verbatim).
 */
export function escapeTemplateText(value: string): string {
  return value.replaceAll('`', '\\`').replaceAll('${', '\\${');
}

/** Drop a trailing slash and normalise separators so script text is stable across platforms. */
export function normalizePath(value: string): string {
  return value.replaceAll('\\', '/').replace(/\/+$/, '');
}

/** Collapse every run of whitespace into a single space (used by short, stable persona text). */
export function singleLine(value: string): string {
  return value.replace(/\s+/g, ' ').trim();
}

/**
 * Split a shell-form command line into tokens, honouring single and double quotes (quotes are
 * dropped, as a shell would). The generator never runs these commands — the runner resolves them
 * and `world.run` gets a fixed argv — this only echoes the task's own commands back in its brief,
 * so a quoted argument stays one token instead of being torn apart.
 */
export function splitCommandLine(line: string): readonly string[] {
  const tokens: string[] = [];
  let current = '';
  let quote: '"' | "'" | undefined;
  let started = false;
  for (const char of line.trim()) {
    if (quote !== undefined) {
      if (char === quote) quote = undefined;
      else current += char;
      continue;
    }
    if (char === '"' || char === "'") {
      quote = char;
      started = true;
      continue;
    }
    if (/\s/.test(char)) {
      if (started) tokens.push(current);
      current = '';
      started = false;
      continue;
    }
    current += char;
    started = true;
  }
  if (started) tokens.push(current);
  return tokens;
}

/** The literal argv array for a world.run call, e.g. `["--silent", "check"]`. */
export function argsLiteral(command: ValidationCommand): string {
  const args = command.args ?? [];
  return `[${args.map(stringLiteral).join(', ')}]`;
}

/** A `//` comment body that can never terminate the comment or start a new line. */
export function commentText(value: string): string {
  return value.replaceAll('*/', '* /').replace(/[\r\n\u2028\u2029]+/g, ' ');
}

/** A persona: short, stable, derived only from the task. Never carries the plan. */
export function personaFor(title: string): string {
  const text = singleLine(title);
  return text.length > 0
    ? `Mission worker for one plan task: ${text}`
    : 'Mission worker for one plan task.';
}

/**
 * The static head of every generated script: the typed-ask payload interface (runner spec §5,
 * field for field), the report shape, and the two helpers that make the four-line validation
 * block possible.
 *
 * The interfaces are plain `interface` declarations, not `declare` ones: the harness synthesizes
 * each typed ask's runtime schema from the declaration in the script.
 */
export function emitHeader(): string {
  return [
    '// Generated by @zcode/projects-mission compilePlanToScript — do not edit by hand.',
    '',
    '/** One task result, as submitted by a worker (runner spec §5). */',
    'interface TaskOutcome {',
    '  status: "done" | "blocked";',
    '  summary: string;',
    '  filesChanged: string[];',
    '  acceptance: { criterion: string; met: boolean; evidence: string }[];',
    '  validationCommands: string[];',
    '  blockers: string[];',
    '}',
    '',
    '/** What the run returns: every task outcome plus the exit code of every validation. */',
    'interface MissionReport {',
    '  tasks: TaskOutcome[];',
    '  validations: { command: string; exitCode: number }[];',
    '}',
    '',
    'const taskOutcomes: TaskOutcome[] = [];',
    'const validationOutcomes: { command: string; exitCode: number }[] = [];',
    '',
    '/** The outcome every failure path produces: blocked, carrying the reason it could not finish. */',
    'function blockedOutcome(reason: string): TaskOutcome {',
    '  return { status: "blocked", summary: reason, filesChanged: [], acceptance: [],',
    '    validationCommands: [], blockers: [reason] };',
    '}',
    '',
    '/** Record one validation result: null = the command never produced an exit code at all. */',
    'function recordValidation(command: string, exitCode: number | null): void {',
    '  if (exitCode === null) return;',
    '  validationOutcomes.push({ command: command, exitCode: exitCode });',
    '}',
    '',
    '/** The exit code of one settled world.run, or null when the command could not run. */',
    'function exitCodeOf(settled: { ok: true; result: WorldRunResult } | { ok: false; error: unknown }): number | null {',
    '  return settled.ok ? settled.result.exitCode : null;',
    '}',
  ].join('\n');
}
